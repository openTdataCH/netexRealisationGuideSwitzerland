#!/usr/bin/env python3
"""
Check relative links in markdown files and warn if target files don't exist.

The markdown sources contain links that are already prepared for the generated
web site (see tools/toolchain.py), not for the source tree. This checker maps
such links back to the files they are generated from:

- ``site/tables/<Name>.md`` / ``site/tables/<Name>.html``
  are generated by the md_builder from ``<docs>/templates/<Name>.xml``
- ``site/xml-snippets/<Name>.xml``
  is generated by the xml_snippets tool from ``<docs>/templates/<Name>.xml``
- ``<Page>.html`` next to a markdown file is rendered by Jekyll from
  ``<Page>.md``
- ``xcore/netex/elements/<Element>.html`` and ``site/netex-html/<Element>.html``
  are generated by the xcore tool from the NeTEx XSD (not part of the automated
  build); the element name is checked against the XSD.

Links that leave the docs folder but stay inside the project folder (e.g.
``../../tools/...`` from ``src/templates/README.md``) are checked against the
file system.
"""

import argparse
import os
import re

from tools.configuration import DOCS_DIR, XSD_FILE_PATH
from tools.safe_path import safe_join

# Repository root (this file lives in <project>/tools/check_links/)
PROJECT_ROOT = os.path.dirname(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

# Links to generated site content, e.g. "../site/tables/StopPlace.md" or
# "site/tables/StopPlace.html" (as generated into A5_annex_index.md)
SITE_TABLES_LINK = re.compile(r"^(?:\.\./)*site/tables/([^/]+)\.(?:md|html)$")
SITE_XML_SNIPPETS_LINK = re.compile(r"^(?:\.\./)*site/xml-snippets/([^/]+)\.xml$")
# Links to the generated NeTEx element documentation (xcore), e.g.
# "../xcore/netex/elements/StopPlace.html" or "../site/netex-html/StopPlace.html"
XCORE_ELEMENT_LINK = re.compile(
    r"^(?:\.\./)*(?:xcore/netex/elements|site/netex-html)/([^/]+)\.html$"
)
# Element declarations in the NeTEx XSD (<element ...> or <xsd:element ...>)
XSD_ELEMENT_DECLARATION = re.compile(
    r"<(?:[A-Za-z_][\w.-]*:)?element\s+name=\"([^\"]+)\""
)


def load_xsd_element_names(xsd_dir):
    """Collect all element names declared in the NeTEx XSD.

    Returns None if the XSD is not available (e.g. the xsd submodule is not
    checked out).
    """
    if not os.path.isdir(xsd_dir):
        return None
    element_names = set()
    for root, dirs, files in os.walk(xsd_dir):
        for file in files:
            if file.lower().endswith(".xsd"):
                file_path = os.path.join(root, file)
                with open(file_path, "r", encoding="utf-8", errors="replace") as f:
                    element_names.update(XSD_ELEMENT_DECLARATION.findall(f.read()))
    return element_names


def get_target_file_path(target_path: str):
    """Gets the file path removing the anchor part."""
    target_file_path = target_path
    hash_start = target_path.rfind("#")
    if hash_start > 1:
        target_file_path = target_path[:hash_start]
    return target_file_path


def resolve_link(link_url, file_dir, templates_dir, xsd_element_names, link_root):
    """Resolve a relative markdown link (anchor already removed).

    Returns a tuple (status, target_path, note):
    - ("check", path, note): the link is valid if path exists
    - ("ok", None, note): the link target is valid (checked without a file)
    - ("skip", None, note): the link target cannot be checked
    - ("broken", None, note): the link target is known to be invalid

    Raises ValueError if the link escapes the link root.
    """
    # Links into the generated site folder are checked against the source
    # files the content is generated from. The site folder is a build
    # artifact excluded from git - it may not exist or be outdated.
    match = SITE_TABLES_LINK.match(link_url)
    if match:
        return (
            "check",
            os.path.join(templates_dir, match.group(1) + ".xml"),
            "site/tables page is generated from this template",
        )

    match = SITE_XML_SNIPPETS_LINK.match(link_url)
    if match:
        return (
            "check",
            os.path.join(templates_dir, match.group(1) + ".xml"),
            "xml snippet is generated from this template",
        )

    match = XCORE_ELEMENT_LINK.match(link_url)
    if match:
        if xsd_element_names is None:
            return (
                "skip",
                None,
                "xcore documentation (NeTEx XSD not available - not checked)",
            )
        element_name = match.group(1)
        if element_name in xsd_element_names:
            return "ok", None, f"NeTEx element '{element_name}' found in the XSD"
        return (
            "broken",
            None,
            f"no element '{element_name}' declared in the NeTEx XSD",
        )

    # Convert relative link to an absolute path, relative to the markdown file
    target_path = os.path.normpath(os.path.join(file_dir, link_url))

    # Prevent path traversal: the link must stay within the link root.
    # Links may leave the docs folder (e.g. "../site/..." and "../../tools/..."
    # from src), but not the link root.
    target_path = safe_join(link_root, os.path.relpath(target_path, link_root))

    # Jekyll renders every markdown page to an html page with the same name
    # (e.g. A5_annex_index.md links to "05_stops.html")
    if target_path.endswith(".html"):
        md_path = target_path[: -len(".html")] + ".md"
        if os.path.exists(md_path):
            return "check", md_path, "html page is rendered from this markdown file"

    return "check", target_path, None


def print_link_message(prefix, file_path, docs_folder, link_text, link_url, details):
    print(f"{prefix} in {os.path.relpath(file_path, docs_folder)}")
    print(f"  Link text: '{link_text}'")
    print(f"  Link URL: '{link_url}'")
    for line in details:
        print(f"  {line}")
    print()


def check_markdown_links(docs_folder):
    """Check all relative links in markdown files."""
    markdown_extensions = (".md", ".MD", ".markdown", ".Markdown")
    link_pattern = r"\[([^\]]+)\]\(([^)]+)\)"

    total_links = 0
    working_links = 0
    broken_links = 0
    skipped_links = 0
    backslash_warnings = 0

    # Convert to absolute paths for consistent resolution
    docs_folder = os.path.abspath(docs_folder)
    templates_dir = os.path.join(docs_folder, "templates")

    # Links may leave the docs folder but must stay within the link root.
    # For the docs of this repository that is the project folder (links reach
    # e.g. ../site/... and ../../tools/...). For a docs folder outside the
    # project, links must stay within its parent folder.
    docs_real = os.path.realpath(docs_folder)
    project_real = os.path.realpath(PROJECT_ROOT)
    if docs_real.startswith(project_real + os.sep):
        link_root = project_real
    else:
        link_root = os.path.dirname(docs_real)
    xsd_dir = os.path.normpath(os.path.dirname(str(XSD_FILE_PATH)))
    xsd_element_names = load_xsd_element_names(xsd_dir)
    if xsd_element_names is None:
        print(f"INFO: NeTEx XSD not found at {xsd_dir}")
        print("  Links to the xcore element documentation will be skipped.\n")

    print(f"Checking relative links in folder {docs_folder}")

    for root, dirs, files in os.walk(docs_folder):
        for file in files:
            if file.endswith(markdown_extensions):
                file_path = os.path.join(root, file)
                with open(file_path, "r", encoding="utf-8") as f:
                    content = f.read()

                # Find all markdown links
                for match in re.finditer(link_pattern, content):
                    link_text = match.group(1)
                    link_url = match.group(2).strip()

                    # Remove an optional quoted title: [text](url "title")
                    link_url = re.split(r'\s+(?=["\'(])', link_url, maxsplit=1)[0]

                    # Skip absolute URLs and anchor links
                    if link_url.startswith(("http://", "https://", "#")):
                        continue

                    # Check for backslashes and warn
                    if "\\" in link_url:
                        backslash_warnings += 1
                        print(
                            f"WARNING: Backslash found in link in {os.path.relpath(file_path, docs_folder)}"
                        )
                        print(f"  Link text: '{link_text}'")
                        print(f"  Link URL: '{link_url}'")
                        print(
                            "  Please use forward slashes (/) for cross-platform compatibility"
                        )
                        print()

                    total_links += 1

                    # A relative link URL must not contain whitespace (an
                    # unquoted rest after a space is not a valid link title,
                    # the link would not work on the generated site)
                    if re.search(r"\s", link_url):
                        broken_links += 1
                        print_link_message(
                            "WARNING: Broken link",
                            file_path,
                            docs_folder,
                            link_text,
                            link_url,
                            ["Note: link URL contains whitespace"],
                        )
                        continue

                    # Remove the anchor part
                    target_file = get_target_file_path(link_url)

                    # Map the link to the file that must exist for it
                    file_dir = os.path.dirname(file_path)
                    try:
                        status, target_path, note = resolve_link(
                            target_file,
                            file_dir,
                            templates_dir,
                            xsd_element_names,
                            link_root,
                        )
                    except ValueError:
                        broken_links += 1
                        print_link_message(
                            "WARNING: Path traversal blocked in link",
                            file_path,
                            docs_folder,
                            link_text,
                            link_url,
                            [],
                        )
                        continue

                    if status == "skip":
                        skipped_links += 1
                        print_link_message(
                            "INFO: Skipped link",
                            file_path,
                            docs_folder,
                            link_text,
                            link_url,
                            [f"Reason: {note}"],
                        )
                        continue

                    if status == "broken":
                        broken_links += 1
                        print_link_message(
                            "WARNING: Broken link",
                            file_path,
                            docs_folder,
                            link_text,
                            link_url,
                            [f"Note: {note}"],
                        )
                        continue

                    if status == "ok":
                        working_links += 1
                        continue

                    # status == "check": verify that the target file exists
                    # Convert absolute path back to relative path for display (using forward slashes)
                    rel_target_path = os.path.relpath(target_path, docs_folder)
                    rel_target_path = rel_target_path.replace(os.sep, "/")

                    if not os.path.exists(target_path):
                        broken_links += 1
                        details = [
                            f"Expected at: {rel_target_path}",
                            f"Target file path: '{target_path}'",
                        ]
                        if note:
                            details.append(f"Note: {note}")
                        print_link_message(
                            "WARNING: Broken link",
                            file_path,
                            docs_folder,
                            link_text,
                            link_url,
                            details,
                        )
                    else:
                        working_links += 1

    print("\nLink checking summary:")
    print(f"  Total relative links checked: {total_links}")
    print(f"  Working links: {working_links}")
    print(f"  Broken links: {broken_links}")
    if skipped_links > 0:
        print(f"  Skipped links (not checkable): {skipped_links}")
    if backslash_warnings > 0:
        print(f"  Backslash warnings: {backslash_warnings}")

    if broken_links == 0 and backslash_warnings == 0:
        print("  Status: All links are valid! :)")
    else:
        status_messages = []
        if broken_links > 0:
            status_messages.append(f"Found {broken_links} broken links")
        if backslash_warnings > 0:
            status_messages.append(f"Found {backslash_warnings} backslash warnings")
        print(f"  Status: {', '.join(status_messages)} :(")


def main():
    parser = argparse.ArgumentParser(
        description="Check relative links in markdown files."
    )
    parser.add_argument(
        "--docs",
        default=DOCS_DIR,
        help=f"Documentation folder to process (default: {DOCS_DIR})",
    )
    args = parser.parse_args()

    check_markdown_links(args.docs)


if __name__ == "__main__":
    main()
